/* ————— Hero backdrop: engineering grid + drifting glow + particles ————— */

function HeroBackdrop() {
  const canvasRef = useRef<HTMLCanvasElement>(null)

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return
    const ctx = canvas.getContext("2d")!
    let raf: number
    let t = 0

    function resize() {
      canvas!.width = canvas!.offsetWidth
      canvas!.height = canvas!.offsetHeight
    }
    resize()
    window.addEventListener("resize", resize)

    const particles = Array.from({ length: 90 }, () => ({
      x: Math.random(),
      y: Math.random(),
      r: Math.random() * 1.4 + 0.3,
      speed: Math.random() * 0.00012 + 0.00004,
      opacity: Math.random() * 0.5 + 0.08,
    }))

    function draw() {
      const w = canvas!.width
      const h = canvas!.height
      ctx.clearRect(0, 0, w, h)

      // Base
      ctx.fillStyle = "#07070d"
      ctx.fillRect(0, 0, w, h)

      // Engineering grid
      const grid = 56
      ctx.strokeStyle = "rgba(99, 102, 241, 0.055)"
      ctx.lineWidth = 1
      ctx.beginPath()
      for (let gx = 0; gx <= w; gx += grid) {
        ctx.moveTo(gx + 0.5, 0)
        ctx.lineTo(gx + 0.5, h)
      }
      for (let gy = 0; gy <= h; gy += grid) {
        ctx.moveTo(0, gy + 0.5)
        ctx.lineTo(w, gy + 0.5)
      }
      ctx.stroke()

      // Drifting glow orbs
      const orbs = [
        {
          x: 0.24 + Math.sin(t * 0.4) * 0.05,
          y: 0.34 + Math.cos(t * 0.3) * 0.05,
          r: 0.42,
          color: "#6366f1",
          a: 0.13,
        },
        {
          x: 0.78 + Math.cos(t * 0.25) * 0.05,
          y: 0.3 + Math.sin(t * 0.35) * 0.06,
          r: 0.34,
          color: "#8b5cf6",
          a: 0.11,
        },
        {
          x: 0.6 + Math.sin(t * 0.18) * 0.04,
          y: 0.75 + Math.cos(t * 0.22) * 0.05,
          r: 0.28,
          color: "#c026d3",
          a: 0.07,
        },
        {
          x: 0.1 + Math.cos(t * 0.3) * 0.03,
          y: 0.85 + Math.sin(t * 0.26) * 0.04,
          r: 0.24,
          color: "#312e81",
          a: 0.1,
        },
      ]
      for (const orb of orbs) {
        const g = ctx.createRadialGradient(
          orb.x * w,
          orb.y * h,
          0,
          orb.x * w,
          orb.y * h,
          orb.r * w,
        )
        g.addColorStop(
          0,
          orb.color +
            Math.round(orb.a * 255)
              .toString(16)
              .padStart(2, "0"),
        )
        g.addColorStop(1, orb.color + "00")
        ctx.fillStyle = g
        ctx.fillRect(0, 0, w, h)
      }

      // Rising particles
      for (const p of particles) {
        p.y -= p.speed
        if (p.y < 0) p.y = 1
        ctx.beginPath()
        ctx.arc(p.x * w, p.y * h, p.r, 0, Math.PI * 2)
        ctx.fillStyle = `rgba(167, 139, 250, ${p.opacity})`
        ctx.fill()
      }

      // Horizon glow line
      const hy = h * 0.72
      const hg = ctx.createLinearGradient(0, hy - 60, 0, hy + 60)
      hg.addColorStop(0, "rgba(139, 92, 246, 0)")
      hg.addColorStop(0.5, "rgba(139, 92, 246, 0.05)")
      hg.addColorStop(1, "rgba(139, 92, 246, 0)")
      ctx.fillStyle = hg
      ctx.fillRect(0, hy - 60, w, 120)

      // Vignette
      const vig = ctx.createRadialGradient(
        w / 2,
        h / 2,
        h * 0.25,
        w / 2,
        h / 2,
        h * 0.95,
      )
      vig.addColorStop(0, "rgba(0,0,0,0)")
      vig.addColorStop(1, "rgba(4,4,9,0.75)")
      ctx.fillStyle = vig
      ctx.fillRect(0, 0, w, h)

      t += 0.008
      raf = requestAnimationFrame(draw)
    }

    draw()
    return () => {
      cancelAnimationFrame(raf)
      window.removeEventListener("resize", resize)
    }
  }, [])

  return (
    <canvas
      ref={canvasRef}
      className="absolute inset-0 w-full h-full"
      style={{ display: "block" }}
      aria-hidden="true"
    />
  )
}

